/**
 * \brief Returns the smaller of two values.
 *
 * \par Requirements:
 *  - 001 This function shall return b when b is less than a, and a otherwise.
 *
 * \param[in] a   First value
 * \param[in] b   Second value
 *
 * \retval    float64_t   The smaller value; a when the values are equal or unordered.
 */
float64_t FACEOE_Utl_Min(float64_t a, float64_t b);

/*************************************************************************************************/
/**
 * \brief Returns the larger of two values.
 *
 * \par Requirements:
 *  - 001 This function shall return b when b is greater than a, and a otherwise.
 *
 * \param[in] a   First value
 * \param[in] b   Second value
 *
 * \retval    float64_t   The larger value; a when the values are equal or unordered.
 */
float64_t FACEOE_Utl_Max(float64_t a, float64_t b);

