/**
 * \par Details:
 *  Inspects entries with fstatat on the open directory, so no full paths are built; an entry
 *  that cannot be inspected is skipped.
 */
bool_t OS_File_EnumerateFiles(const char_t* folderPath, OS_File_Visitor_t visitor, void* context)
{
    DIR*           directory;
    struct dirent* entry;
    struct stat    file_status;
    bool_t         result;

    LOGASSERT(NULL != folderPath);
    LOGASSERT(NULL != visitor);
    result    = FALSE;
    directory = opendir(folderPath);
    if (NULL != directory)
    {
        do
        {
            errno = 0;
            entry = readdir(directory);
            if (NULL != entry)
            {
                if (0 == fstatat(dirfd(directory), entry->d_name, &file_status, 0))
                {
                    if (S_ISREG(file_status.st_mode))
                    {
                        visitor(entry->d_name, context);
                    }
                }
            }
        } while (NULL != entry);
        result = (0 == errno);
        if (0 != closedir(directory))
        {
            result = FALSE;
        }
    }

    return result;
}
