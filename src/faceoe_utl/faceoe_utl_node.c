/*************************************************************************************************/
/**
 * \par Details:
 *  The item may be NULL, for a node that stands only for its children.
 */
void FACEOE_Utl_Node_Initialize(FACEOE_Utl_Node_t* node, const void* item)
{
    LOGASSERT(NULL != node);

    (void)memset(node, 0, sizeof((*node)));
    node->item        = item;
    node->parent      = NULL;
    node->firstChild  = NULL;
    node->lastChild   = NULL;
    node->nextSibling = NULL;
}

/*************************************************************************************************/
/**
 * \par Details:
 *  Keeping the last child makes appending constant time. Cycles are not checked.
 */
void FACEOE_Utl_Node_AppendChild(FACEOE_Utl_Node_t* parent, FACEOE_Utl_Node_t* child)
{
    LOGASSERT(NULL != parent);
    LOGASSERT(NULL != child);
    LOGASSERT(NULL == child->parent);
    LOGASSERT(NULL == child->nextSibling);

    if (NULL != parent->lastChild)
    {
        // Place the new child after the existing children
        parent->lastChild->nextSibling = child;
    }
    else
    {
        // The new child is also the first child of an empty parent
        parent->firstChild = child;
    }

    parent->lastChild = child;
    child->parent     = parent;
}
