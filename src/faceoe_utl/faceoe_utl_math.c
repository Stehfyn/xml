/*************************************************************************************************/
/**
 * \par Details:
 *  A NaN in either argument makes the comparison false, so a is returned.
 */
float64_t FACEOE_Utl_Min(float64_t a, float64_t b)
{
    if (b < a)
    {
        return b;
    }

    return a;
}

/*************************************************************************************************/
/**
 * \par Details:
 *  A NaN in either argument makes the comparison false, so a is returned.
 */
float64_t FACEOE_Utl_Max(float64_t a, float64_t b)
{
    if (b > a)
    {
        return b;
    }

    return a;
}
